-- Coupons (discount codes entered at checkout), their redemptions by orders, the discount of an
-- order, and indexes for the statistics of the administration dashboard.

CREATE TABLE coupons
(
    id                  BIGSERIAL PRIMARY KEY,
    -- stored in upper case, entered case-insensitively
    code                VARCHAR(30)    NOT NULL,
    description         VARCHAR(255),
    discount_type       VARCHAR(20)    NOT NULL,
    discount_value      NUMERIC(14, 2) NOT NULL,
    min_order_amount    NUMERIC(14, 2),
    -- cap of a percentage discount
    max_discount_amount NUMERIC(14, 2),
    starts_at           TIMESTAMPTZ,
    expires_at          TIMESTAMPTZ,
    usage_limit         INT,
    -- number of redemptions not released by a cancellation
    used_count          INT            NOT NULL DEFAULT 0,
    per_user_limit      INT,
    active              BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    version             BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_coupons_code UNIQUE (code),
    CONSTRAINT ck_coupons_code CHECK (code ~ '^[A-Z0-9_-]{3,30}$'),
    CONSTRAINT ck_coupons_discount_type CHECK (discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT ck_coupons_discount_value CHECK (discount_value > 0
        AND (discount_type <> 'PERCENTAGE' OR discount_value <= 100)),
    CONSTRAINT ck_coupons_min_order_amount CHECK (min_order_amount IS NULL OR min_order_amount > 0),
    CONSTRAINT ck_coupons_max_discount_amount CHECK (max_discount_amount IS NULL OR max_discount_amount > 0),
    CONSTRAINT ck_coupons_period CHECK (starts_at IS NULL OR expires_at IS NULL OR expires_at > starts_at),
    CONSTRAINT ck_coupons_limits CHECK ((usage_limit IS NULL OR usage_limit > 0)
        AND (per_user_limit IS NULL OR per_user_limit > 0) AND used_count >= 0)
);

CREATE INDEX idx_coupons_created ON coupons (created_at DESC);

-- One redemption per order; released (not deleted) when the order is cancelled
CREATE TABLE coupon_redemptions
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id       BIGINT         NOT NULL,
    order_id        UUID           NOT NULL,
    user_id         UUID           NOT NULL,
    discount_amount NUMERIC(14, 2) NOT NULL,
    created_at      TIMESTAMPTZ    NOT NULL,
    released_at     TIMESTAMPTZ,
    CONSTRAINT fk_coupon_redemptions_coupon FOREIGN KEY (coupon_id) REFERENCES coupons (id),
    CONSTRAINT fk_coupon_redemptions_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT uk_coupon_redemptions_order UNIQUE (order_id),
    CONSTRAINT ck_coupon_redemptions_amount CHECK (discount_amount >= 0)
);

CREATE INDEX idx_coupon_redemptions_coupon_user ON coupon_redemptions (coupon_id, user_id) WHERE released_at IS NULL;

ALTER TABLE orders
    ADD COLUMN coupon_code     VARCHAR(30),
    ADD COLUMN discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0;

ALTER TABLE orders DROP CONSTRAINT ck_orders_amounts;
ALTER TABLE orders ADD CONSTRAINT ck_orders_amounts CHECK (subtotal > 0 AND shipping_fee >= 0
    AND discount_amount >= 0 AND discount_amount <= subtotal
    AND total_amount = subtotal - discount_amount + shipping_fee);
ALTER TABLE orders ADD CONSTRAINT ck_orders_discount_of_coupon CHECK (coupon_code IS NOT NULL OR discount_amount = 0);

-- Statistics: orders created and orders paid in a period
CREATE INDEX idx_orders_created ON orders (created_at);
CREATE INDEX idx_orders_paid ON orders (paid_at) WHERE paid_at IS NOT NULL;

