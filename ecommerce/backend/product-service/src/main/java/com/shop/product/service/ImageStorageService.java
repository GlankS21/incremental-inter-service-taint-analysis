package com.shop.product.service;

import com.shop.product.dto.response.UploadedImageResponse;
import org.springframework.core.io.Resource;
import org.springframework.http.MediaType;
import org.springframework.web.multipart.MultipartFile;

/**
 * Product images uploaded by administrators, stored on the local file system (a Docker volume in
 * production) and served by product-service itself. Files are never deleted: an image that no
 * product refers to any more stays on disk.
 */
public interface ImageStorageService {

    /**
     * Stores a JPEG, PNG, WebP or GIF image (recognised by its content) under a random name.
     *
     * @throws com.shop.common.exception.BadRequestException when the file is empty, too large or not
     *                                                       a supported image
     */
    UploadedImageResponse store(MultipartFile file);

    /**
     * @throws com.shop.common.exception.ResourceNotFoundException when the name is not one generated by
     *                                                             {@link #store} or the file is missing
     */
    StoredImage load(String filename);

    record StoredImage(Resource resource, MediaType contentType, long size) {
    }
}
