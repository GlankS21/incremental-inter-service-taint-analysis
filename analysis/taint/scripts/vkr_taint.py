"""vkr-taint: incremental inter-service taint analysis of a Spring Cloud repository in one command.

    vkr-taint <repo> [--build auto|mvn|docker|none] [--baseline report.json] [--gate] [--out DIR]

1. configuration: <repo>/vkr-taint.yml when present (or --config); otherwise one is generated in
   the work dir with everything detected (services, shared modules, sources, the sinks of every built-in catalogue)
2. build (the tool needs target/classes and the Spring Boot jar of each service):
     auto    build with Maven when a service has no built artifacts, else use them
     mvn     <repo>/mvnw or mvn on this machine: -B -DskipTests package (trusted code, e.g. CI)
     docker  in a Maven container, the sources copied in and the build copied out to the work dir,
             so the repo's build plugins never run on this machine (untrusted code; --image)
     none    use what is built
3. incremental.py: per-service Micans runs, cached in the work dir by content hash, composed along
   the channel model (HTTP, AMQP, shared tables) into chains from an endpoint to a sink
4. <out>/vkr-taint-report.json and <out>/vkr-taint.sarif (with --baseline: baselineState new/unchanged)

exit: 0, or with --gate (or gate.fail-on: new-chains) 1 on new findings and 2 when a service failed;
      3 on a configuration or build error
env:  JAVA_HOME (JDK 21+ running Micans), VKR_MICANS_JAR (the patched Micans jar),
      VKR_CHANNEL_EXTRACTOR (channel-extractor jar, default: analysis/channel-extractor/target),
      VKR_WORK (work dir with the cache, default ~/.cache/vkr-taint/<repo>-<hash>), VKR_HEAP (default 8g)
"""
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sarif  # noqa: E402
import vkr_config  # noqa: E402

BUILD_PUBLIC = os.path.join(HERE, os.pardir, os.pardir, 'experiments', 'public', 'build_public.sh')
GENERATED = """\
# generated by vkr-taint: every part is detected from the repository
version: 1
project:
  root: {root}
  gateway-config: auto
services: auto
shared: auto
taint:
  sinks: [cwe-89, cwe-117, cwe-79, cwe-918, cwe-1336]
  sources: auto
  discovery: annotations
analysis:
  context: 1-call
  heap: ${{VKR_HEAP:-8g}}
  world-cache: off
toolchain:
  java-home: ${{JAVA_HOME}}
  micans-jar: ${{VKR_MICANS_JAR:-${{MICANS_JAR}}}}
gate:
  fail-on: none
"""


def fail(msg):
    print(f'vkr-taint: {msg}', file=sys.stderr)
    sys.exit(3)


def default_work(repo):
    base = os.environ.get('XDG_CACHE_HOME') or os.path.join(os.path.expanduser('~'), '.cache')
    tag = hashlib.sha256(os.path.abspath(repo).encode()).hexdigest()[:8]
    return os.path.join(base, 'vkr-taint', f'{os.path.basename(os.path.abspath(repo))}-{tag}')


def write_config(work, root):
    path = os.path.join(work, 'vkr-taint.yml')
    os.makedirs(work, exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(GENERATED.format(root=json.dumps(os.path.abspath(root).replace(os.sep, '/'))))
    return path


def missing_artifacts(config):
    try:
        vkr_config.load(config, require=('artifacts',))
        return None
    except vkr_config.ConfigError as e:
        return str(e)


def build_mvn(repo, mvn_args):
    wrapper = os.path.join(repo, 'mvnw.cmd' if os.name == 'nt' else 'mvnw')
    mvn = wrapper if os.path.isfile(wrapper) else shutil.which('mvn')
    if not mvn:
        fail('no ./mvnw and no mvn on PATH; build the project first or use --build docker')
    cmd = [mvn, '-B', '-q', '-DskipTests', *mvn_args, 'package']
    print('build:', ' '.join(cmd), flush=True)
    if subprocess.run(cmd, cwd=repo).returncode:
        fail('the Maven build failed')


def build_docker(repo, dest, image, mvn_args):
    if not os.path.isdir(os.path.join(repo, '.git')):
        fail('--build docker needs a git clone (the built commit is recorded)')
    print(f'build: {image} in a container -> {dest}', flush=True)
    if subprocess.run(['sh', BUILD_PUBLIC, repo, dest, image, *mvn_args]).returncode:
        fail('the container build failed, see the output above')


def main():
    ap = argparse.ArgumentParser(prog='vkr-taint', description=__doc__.split('\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument('repo', help='repository root (a Maven multi-module Spring Cloud project)')
    ap.add_argument('--config', help='vkr-taint.yml (default: <repo>/vkr-taint.yml, else generated)')
    ap.add_argument('--build', choices=('auto', 'mvn', 'docker', 'none'), default='auto')
    ap.add_argument('--image', default='maven:3.9.9-eclipse-temurin-17', help='Maven image for --build docker')
    ap.add_argument('--mvn-arg', action='append', default=[], help='extra Maven argument (repeatable)')
    ap.add_argument('--services', help='analyse only these services (comma-separated)')
    ap.add_argument('--baseline', help='earlier vkr-taint-report.json: report new and removed findings')
    ap.add_argument('--out', default='vkr-taint-out', help='directory for the report and SARIF')
    ap.add_argument('--work', help='work dir with the analysis cache (default: $VKR_WORK or ~/.cache/vkr-taint/...)')
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--gate', action='store_true', help='exit 1 on new findings, 2 on a failed service')
    g.add_argument('--no-gate', action='store_true')
    a = ap.parse_args()

    repo = os.path.abspath(a.repo)
    if not os.path.isdir(repo):
        fail(f'not a directory: {a.repo}')
    work = os.path.abspath(a.work or os.environ.get('VKR_WORK') or default_work(repo))
    own = a.config or (os.path.join(repo, vkr_config.CONFIG_NAME)
                       if os.path.isfile(os.path.join(repo, vkr_config.CONFIG_NAME)) else None)
    if a.build == 'docker' and own:
        fail('--build docker analyses the build copied out of the container, which a vkr-taint.yml of '
             'the repo does not point at; use --build mvn|none with it')
    root = os.path.join(work, 'build', os.path.basename(repo)) if a.build == 'docker' else repo
    config = os.path.abspath(own) if own else write_config(work, root)
    print(f'config: {config}\nwork:   {work}', flush=True)

    if a.build == 'docker':
        build_docker(repo, root, a.image, a.mvn_arg)
    elif a.build == 'mvn' or (a.build == 'auto' and missing_artifacts(config)):
        build_mvn(repo, a.mvn_arg)
    problem = missing_artifacts(config)
    if problem:
        fail(problem)

    os.makedirs(a.out, exist_ok=True)
    report = os.path.abspath(os.path.join(a.out, 'vkr-taint-report.json'))
    cmd = [sys.executable, '-I', os.path.join(HERE, 'incremental.py'), '--config', config, '--out', report]
    cmd += ['--services', a.services] if a.services else []
    cmd += ['--baseline', os.path.abspath(a.baseline)] if a.baseline else []
    cmd += ['--gate'] if a.gate else ['--no-gate'] if a.no_gate else []
    env = dict(os.environ, VKR_WORK=work, PYTHONUTF8='1')
    code = subprocess.run(cmd, env=env).returncode
    if not os.path.isfile(report) or code not in (0, 1, 2):
        sys.exit(code or 3)

    cfg_root = vkr_config.load(config)['root']
    out = os.path.join(a.out, 'vkr-taint.sarif')
    doc = sarif.to_sarif(json.load(open(report, encoding='utf-8')),
                         json.load(open(os.path.join(work, 'channels.json'), encoding='utf-8')), cfg_root,
                         json.load(open(a.baseline, encoding='utf-8')) if a.baseline else None)
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(doc, f, indent=1)
    print(f'{len(doc["runs"][0]["results"])} SARIF results -> {out}')
    sys.exit(code)


if __name__ == '__main__':
    main()
